class PDFAnalyzer:
    def __init__(self):
        self.results = {
            'text_content': '',
            'tables': [],
            'horse_data': [],
            'race_info': {},
            'previous_results': []
        }
    
    def analyze_pdf_file(self, uploaded_file):
        """Comprehensive PDF analysis for racing documents"""
        try:
            # Method 1: pdfplumber for text and tables
            uploaded_file.seek(0)
            with pdfplumber.open(uploaded_file) as pdf:
                for page in pdf.pages:
                    # Extract text
                    text = page.extract_text()
                    if text:
                        self.results['text_content'] += text + "\n"
                    
                    # Extract tables
                    tables = page.extract_tables()
                    if tables:
                        self.results['tables'].extend(tables)
            
            # Parse racing-specific data
            self._parse_racing_data()
            
            return self.results
            
        except Exception as e:
            st.error(f"PDF analysis error: {str(e)}")
            return None
    
    def _parse_racing_data(self):
        """Extract structured racing data from PDF text"""
        lines = self.results['text_content'].split('\n')
        current_horse = None
        
        for i, line in enumerate(lines):
            line = line.strip()
            
            # Detect horse entries (patterns like "1.-HELD& SI", "2.-FURGOS FLIGNAT")
            horse_match = re.match(r'(\d+)\.-\s*([A-Z][A-Z\s&]+)', line)
            if horse_match:
                if current_horse and current_horse.get('horse_name'):
                    self.results['horse_data'].append(current_horse)
                
                current_horse = {
                    'horse_number': int(horse_match.group(1)),
                    'horse_name': horse_match.group(2).strip(),
                    'analysis': '',
                    'jockey': 'Unknown',
                    'trainer': 'Unknown',
                    'win': 0,
                    'position': 0,
                    'is_favorite': 0,
                    'has_experience': 1
                }
            
            # Continue horse analysis text
            elif current_horse and line and not re.match(r'^\d+\.-', line):
                current_horse['analysis'] += ' ' + line
                
                # Extract win information
                if any(word in line.lower() for word in ['gagnant', 'victoire', 'imposé', 'vainqueur']):
                    current_horse['win'] = 1
                
                # Extract favorite information
                if any(word in line.lower() for word in ['favori', 'favorite', 'principal']):
                    current_horse['is_favorite'] = 1
            
            # Detect race information
            elif 'GRAND NATIONAL' in line.upper():
                self.results['race_info']['name'] = line
            elif 'METRES' in line.upper():
                distance_match = re.search(r'(\d+)\s*METRES', line.upper())
                if distance_match:
                    self.results['race_info']['distance'] = f"{distance_match.group(1)}m"
            elif 'EUROS' in line.upper():
                prize_match = re.search(r'(\d+)\s*EUROS', line.upper())
                if prize_match:
                    self.results['race_info']['prize_money'] = prize_match.group(1)
            
            # Detect previous results
            elif 'ARRIVÉE' in line.upper() or 'TIERCE' in line.upper():
                result_data = self._extract_race_results(lines[i:i+10])
                if result_data:
                    self.results['previous_results'].append(result_data)
        
        # Add the last horse
        if current_horse and current_horse.get('horse_name'):
            self.results['horse_data'].append(current_horse)
        
        # Estimate positions for horses
        self._estimate_positions()
    
    def _extract_race_results(self, lines):
        """Extract race results from text lines"""
        for line in lines:
            if 'ARRIVÉE' in line:
                numbers_match = re.findall(r'\b(\d+)\b', line)
                if numbers_match:
                    return {
                        'type': 'Quarte' if 'QUARTE' in line.upper() else 'Tierce',
                        'results': numbers_match,
                        'date': datetime.now().strftime('%Y-%m-%d')
                    }
        return None
    
    def _estimate_positions(self):
        """Estimate positions based on analysis text"""
        for horse in self.results['horse_data']:
            analysis = horse['analysis'].lower()
            
            # Estimate position based on keywords
            if any(word in analysis for word in ['premier', '1er', 'gagnant', 'vainqueur']):
                horse['position'] = 1
            elif any(word in analysis for word in ['deuxième', '2ème', 'second']):
                horse['position'] = 2
            elif any(word in analysis for word in ['troisième', '3ème']):
                horse['position'] = 3
            elif any(word in analysis for word in ['quatrième', '4ème']):
                horse['position'] = 4
            elif any(word in analysis for word in ['cinquième', '5ème']):
                horse['position'] = 5
            else:
                horse['position'] = random.randint(6, 12)
    
    def convert_to_ai_format(self):
        """Convert extracted PDF data to LONAB AI format"""
        converted_horses = []
        
        for horse in self.results['horse_data']:
            converted_horse = {
                'horse_number': horse['horse_number'],
                'horse_name': horse['horse_name'],
                'jockey': horse['jockey'],
                'trainer': horse['trainer'],
                'win': horse['win'],
                'position': horse['position'],
                'date': datetime.now().strftime('%Y-%m-%d'),
                'race_type': 'Quinté+',
                'course': self.results['race_info'].get('name', 'MAUQUENCIN').split('-')[-1].strip(),
                'distance': self.results['race_info'].get('distance', '2850m'),
                'prize_money': self.results['race_info'].get('prize_money', '90000'),
                'is_favorite': horse['is_favorite'],
                'has_experience': horse['has_experience'],
                'weekday': datetime.now().weekday(),
                'month': datetime.now().month
            }
            converted_horses.append(converted_horse)
        
        return converted_horses

